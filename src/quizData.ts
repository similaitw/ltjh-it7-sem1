export const QUIZ_LENGTH = 5;
export const PASSING_SCORE = 4;

export function questionsForLesson(lessonId: string) {
  return quizBank[lessonId] ?? [];
}

export function pickQuiz(lessonId: string, count = QUIZ_LENGTH, random = Math.random) {
  const pool = [...questionsForLesson(lessonId)];
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(count, pool.length));
}
